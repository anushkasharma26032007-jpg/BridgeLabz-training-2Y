package Recursion;

public class multiplefunctioncall {
    static void message(){
        System.out.println("Hello World");
    }
    static void message1(){
        System.out.println("Hello World");
    }
    static void message2(){
        System.out.println("Hello World");
    }
    static void message3(){
        System.out.println("Hello World");
    }
    static void message4(){
        System.out.println("Hello World");
    }
    public static void main(){
        message();
        message1();
        message2();
        message3();
        message4();
    }
}
